export async function tracksForRelease(release: Release): Promise<Track[]> {
  const tracks = await listTracks();
  const byId = new Map(tracks.map((t) => [t.id, t]));
  return release.takeIds
    .map((id) => byId.get(id))
    .filter((t): t is Track => t !== undefined);
}

/** The Critic's verdicts on one act, release by release, newest first. */
export async function criticReviewsForPlayer(
  agentId: string,
): Promise<{ releaseId: string; releaseTitle: string; verdict: string }[]> {
  const releases = await listReleases();
  return releases
    .filter((r) => typeof r.reviews[agentId] === "string")
    .map((r) => ({ releaseId: r.id, releaseTitle: r.title, verdict: r.reviews[agentId] }))
    .reverse();
}

/**
 * The act's single: the Producer's selected take from the newest release
 * that carries a selection for this act. Pure so it's testable; pages call
 * singleForAct below. Returns null when the Producer has never picked for
 * this act (e.g. fixture-only mode, where release 0001 predates the staff).
 */
export function resolveSingle(
  releases: Release[],
  tracks: Track[],
  agentId: string,
): { track: Track; release: Release } | null {
  const byId = new Map(tracks.map((t) => [t.id, t]));
  const newestFirst = [...releases].sort((a, b) => b.id.localeCompare(a.id));
  for (const release of newestFirst) {
    const takeId = release.selections[agentId];
    if (!takeId) continue;
    const track = byId.get(takeId);
    if (track) return { track, release };
  }
  return null;
}

export async function singleForAct(
  agentId: string,
): Promise<{ track: Track; release: Release } | null> {
  const [releases, tracks] = await Promise.all([listReleases(), listTracks()]);
  return resolveSingle(releases, tracks, agentId);
}

/* ————————————————————————————————————————————————————————————————————
 * The Album view: one entity over the catalogue's four shapes.
 *
 * A casual listener sees ARTISTS and ALBUMS. Under the hood an "album" is
 * one of three stored shapes — a session release (AFAR-NNNN), a session
 * tape (TAPE-NNNN, solo tapes included), or an imported back-catalogue
 * album riding its artist's agent row (id T-<slug>, tracks in the tracks
 * table). This is a READ-LAYER unification: nothing migrates, every
 * stored shape keeps its schema, and the views below are derived fresh
 * from the same rows the old pages read.
 *
 * Public ids: the slug is the catalogue number, lowercased — afar-0001,
 * tape-0010, t-lolgorithm. Stable because the underlying ids are stable
 * (CLAUDE.md: entity ids never rename).
 * ———————————————————————————————————————————————————————————————————— */

/**
 * The four shapes in the catalogue:
 * - `record` — a single-artist ALBUM, the primary object now (AFAR-NNNN);
 * - `session` — a round-based multi-artist release, the logged history
 *   (AFAR-0001..0007), append-only and never renamed;
 * - `tape` — a session's full recording (TAPE-NNNN);
 * - `album` — a back-catalogue record an artist brought with them.
 */
export type AlbumType = "record" | "session" | "tape" | "album";

/** One measured pull on a record: which heard album moved it, and how much. */
export interface AlbumPull {
  artistId: string;
  albumId: string;
  title: string;
  weight: number;
}

/** "0001" -> "AFAR-0001" (mirrors lib/acts.catalogueNumber, which imports from here). */
function catalogueNumberOf(releaseId: string): string {
  return `AFAR-${releaseId}`;
}

export interface AlbumTrackView {
  id: string;
  title: string;
  artistId: string;
  durationSec: number | null;
  audioUrl: string | null;
  /** What the artist said about this song, if they said anything. */
  note: string | null;
}

export interface AlbumView {
  /** Public id, used in /album/[slug] URLs. */
  slug: string;
  type: AlbumType;
  /** "AFAR-0001" / "TAPE-0010"; imported albums carry no catalogue number. */
  catalogueNo: string | null;
  title: string;
  /** Every artist on the record, in track order. */
  artistIds: string[];
  /** Sortable release date; imported albums predate the sessions and carry none. */
  date: string | null;
  /** The era line under the title ("2020s"). */
  era: string | null;
  tracks: AlbumTrackView[];
  /**
   * The ARTIST's own framing of the record, written with the songs. Set on
   * single-artist albums; null on the shapes whose sleeve prose was written
   * by someone else (or by nobody).
   */
  description: string | null;
  /** The Archivist's back-of-sleeve prose, whatever shape it rode in on. */
  linerNotes: string | null;
  /** Imported album art; sessions render their graph cover from `influence`. */
  coverUrl: string | null;
  influence: InfluenceEdge[] | null;
  /** Album-cadence influence: which records pulled this one (records only). */
  pulledBy: AlbumPull[];
  /** The depth payload — exactly one of these is set, matching `type`. */
  record: AlbumRecord | null;
  release: Release | null;
  tape: Tape | null;
  importArtistId: string | null;
}

