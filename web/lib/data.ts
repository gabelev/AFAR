/**
 * "afar-0008" | "afar-0001" | "tape-0010" | "t-lolgorithm" — slugs are
 * lowercased catalogue ids. Single-artist albums and the round-based sessions
 * share the `afar-` slug space because they share ONE id sequence: ids are
 * allocated across both tables, so a slug always resolves to exactly one
 * record and old links never change meaning.
 */
export function albumSlug(type: AlbumType, id: string): string {
  if (type === "record" || type === "session") return `afar-${id}`.toLowerCase();
  if (type === "tape") return `tape-${id}`.toLowerCase();
  return id.toLowerCase();
}

/**
 * One artist's album. The tracklist is `trackIds` in the artist's own order —
 * an album is a sequence, not a set, so the order the record was written in is
 * the order it plays in.
 */
function recordAlbum(record: AlbumRecord, tracks: Track[]): AlbumView {
  const byId = new Map(tracks.map((t) => [t.id, t]));
  const own = record.trackIds
    .map((id) => byId.get(id))
    .filter((t): t is Track => t !== undefined);
  const pulledBy = record.influence
    .filter((e) => e.to === record.artistId)
    .map((e) => {
      const heard = record.heard.find((h) => h.artistId === e.from);
      return {
        artistId: e.from,
        albumId: heard?.albumId ?? "",
        title: heard?.title ?? "",
        weight: e.weight,
      };
    })
    .sort((a, b) => b.weight - a.weight);
  return {
    slug: albumSlug("record", record.id),
    type: "record",
    catalogueNo: catalogueNumberOf(record.id),
    title: record.title,
    artistIds: [record.artistId],
    date: record.date,
    era: record.era,
    tracks: own.map((t) => ({
      id: t.id,
      title: t.title,
      artistId: t.agentId,
      durationSec: t.durationSec,
      audioUrl: t.audioUrl,
      note: t.line?.trim() || null,
    })),
    description: record.description,
    linerNotes: record.linerNotes ?? null,
    coverUrl: record.coverUrl,
    influence: null, // the graph cover is the sessions' three-act figure
    pulledBy,
    record,
    release: null,
    tape: null,
    importArtistId: null,
  };
}

function sessionAlbum(release: Release, tracks: Track[]): AlbumView {
  const byId = new Map(tracks.map((t) => [t.id, t]));
  const takes = release.takeIds
    .map((id) => byId.get(id))
    .filter((t): t is Track => t !== undefined);
  return {
    slug: albumSlug("session", release.id),
    type: "session",
    catalogueNo: catalogueNumberOf(release.id),
    title: release.title,
    artistIds: takes.map((t) => t.agentId),
    date: release.date,
    era: release.era,
    tracks: takes.map((t) => ({
      id: t.id,
      title: t.title,
      artistId: t.agentId,
      durationSec: t.durationSec,
      audioUrl: t.audioUrl,
      note: null,
    })),
    description: null,
    linerNotes: release.linerNotes ?? null,
    coverUrl: null,
    influence: release.influence,
    pulledBy: [],
    record: null,
    release,
    tape: null,
    importArtistId: null,
  };
}

function tapeAlbum(tape: Tape): AlbumView {
  const artistIds: string[] = [];
  for (const take of tape.takes) {
    if (!artistIds.includes(take.agentId)) artistIds.push(take.agentId);
  }
  return {
    slug: albumSlug("tape", tape.id),
    type: "tape",
    catalogueNo: tapeNumber(tape.id),
    title: tape.title,
    artistIds,
    date: tape.date,
    era: null,
    tracks: tape.takes.map((take, i) => ({
      id: `${tape.id}-t${i}`,
      title: take.title ?? `Round ${take.round + 1} take`,
      artistId: take.agentId,
      durationSec: take.durationSec ?? null,
      audioUrl: take.audioUrl,
      note: null,
    })),
    description: null,
    linerNotes: tape.linerNotes ?? null,
    coverUrl: null,
    influence: null,
    pulledBy: [],
    record: null,
    release: null,
    tape,
    importArtistId: null,
  };
}

function importAlbum(agent: Agent, tracks: Track[]): AlbumView | null {
  if (!agent.album) return null;
  const own = tracks.filter((t) => t.releaseId === agent.album!.id);
  if (own.length === 0) return null; // no audio imported yet — nothing to stream
  return {
    slug: albumSlug("album", agent.album.id),
    type: "album",
    catalogueNo: null,
    title: agent.album.title,
    artistIds: [agent.id],
    date: null,
    era: agent.genreLine?.split("·")[1]?.trim() ?? null,
    tracks: own.map((t) => ({
      id: t.id,
      title: t.title,
      artistId: t.agentId,
      durationSec: t.durationSec,
      audioUrl: t.audioUrl,
      note: null,
    })),
    description: null,
    linerNotes: agent.album.linerNotes ?? null,
    coverUrl: agent.coverUrl,
    influence: null,
    pulledBy: [],
    record: null,
    release: null,
    tape: null,
    importArtistId: agent.id,
  };
}

/**
 * Every album in the catalogue, one flat list: dated records (single-artist
 * albums, sessions and tapes) newest first, then the imported back catalogues
 * (undated — they predate the sessions) alphabetically. Pure so it's testable.
 */
export function resolveAlbums(
  agents: Agent[],
  releases: Release[],
  tapes: Tape[],
  tracks: Track[],
  records: AlbumRecord[] = [],
): AlbumView[] {
  const dated = [
    ...records.map((r) => recordAlbum(r, tracks)),
    ...releases.map((r) => sessionAlbum(r, tracks)),
    ...tapes.map(tapeAlbum),
  ].sort(
    (a, b) => (b.date ?? "").localeCompare(a.date ?? "") || b.slug.localeCompare(a.slug),
  );
  const imports = agents
    .flatMap((a) => importAlbum(a, tracks) ?? [])
    .sort((a, b) => a.title.localeCompare(b.title));
  return [...dated, ...imports];
}

export async function listAlbums(): Promise<AlbumView[]> {
  const [agents, releases, tapes, tracks, records] = await Promise.all([
    listAgents(),
    listReleases(),
    listTapes(),
    listTracks(),
    listAlbumRecords(),
  ]);
  return resolveAlbums(agents, releases, tapes, tracks, records);
}

export function resolveAlbum(albums: AlbumView[], slug: string): AlbumView | null {
  const wanted = slug.toLowerCase();
  return albums.find((a) => a.slug === wanted) ?? null;
}

export async function getAlbum(slug: string): Promise<AlbumView | null> {
  return resolveAlbum(await listAlbums(), slug);
}

/**
 * An artist's discography: every album they appear on, in the flat
 * catalogue order (newest dated first, their imported record last).
 */
export function resolveDiscography(albums: AlbumView[], artistId: string): AlbumView[] {
  return albums.filter((a) => a.artistIds.includes(artistId));
}

export async function discographyForArtist(artistId: string): Promise<AlbumView[]> {
  return resolveDiscography(await listAlbums(), artistId);
}

/** ONE flat roster — every artist, alphabetical. No sections, no tiers. */
export function resolveArtists(agents: Agent[]): Agent[] {
  return agents
    .filter((a) => a.kind === "player")
    .sort((a, b) => a.displayName.localeCompare(b.displayName));
}

export async function listArtists(): Promise<Agent[]> {
  return resolveArtists(await listAgents());
}

/**
 * The flat roster ordered by latest activity: whoever appears on the
 * newest record leads. Data-driven — no tiers; an artist ranks by their
 * records alone. Ties (and artists with no records yet) stay alphabetical.
 */
export function resolveArtistsByActivity(agents: Agent[], albums: AlbumView[]): Agent[] {
  const rank = new Map<string, number>();
  albums.forEach((album, i) => {
    for (const id of album.artistIds) {
      if (!rank.has(id)) rank.set(id, i);
    }
  });
  return resolveArtists(agents).sort(
    (a, b) => (rank.get(a.id) ?? albums.length) - (rank.get(b.id) ?? albums.length),
  );
}

/** Rationale quotes a player has left on releases, newest first. */
export async function rationalesForPlayer(
  agentId: string,
): Promise<{ releaseId: string; releaseTitle: string; quote: string }[]> {
  const releases = await listReleases();
  return releases
    .filter((r) => typeof r.rationales[agentId] === "string")
    .map((r) => ({ releaseId: r.id, releaseTitle: r.title, quote: r.rationales[agentId] }))
    .reverse();
}
